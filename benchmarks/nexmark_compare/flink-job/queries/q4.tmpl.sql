-- Nexmark q4 on flink, KAFKA-SINK sink variant. Average price per category:
-- auction joined to bid, then aggregated. REDUCED from the official q4, which
-- first takes the maximum bid per auction; this averages every bid in the
-- category, so both engines run one join plus one aggregate. Flink casts the
-- price to DOUBLE explicitly and clink does not, which is a DIALECT
-- difference for the same intent: AVG of an exact numeric type returns an
-- exact numeric type in Flink, so AVG(BIGINT) truncates - measured at 49975.0
-- where clink gives 49975.9 - while clink's AVG already returns a real
-- number. clink cannot take the cast inside AVG (its AVG accepts only a bare
-- column reference), so the cast goes where it is needed.
-- GENERATED by queries/gen_queries.py from the single cross-engine
-- definition. Edit that file, not this one.
CREATE TABLE auction (
  `id` BIGINT, `itemname` STRING, `initialbid` BIGINT, `reserve` BIGINT, `expires` BIGINT, `seller` BIGINT, `category` BIGINT, `datetime` BIGINT,
  ts AS TO_TIMESTAMP_LTZ(`datetime`, 3),
  WATERMARK FOR ts AS ts - INTERVAL '4' SECOND
) WITH (
  'connector' = 'kafka',
  'topic' = 'nx-auction',
  'properties.bootstrap.servers' = 'kafka:29092',
  'properties.group.id' = 'flink-q4-auction',
  'scan.startup.mode' = 'earliest-offset',
  'format' = 'json',
  'json.ignore-parse-errors' = 'false'
);
CREATE TABLE bid (
  `auction` BIGINT, `bidder` BIGINT, `price` BIGINT, `channel` STRING, `url` STRING, `datetime` BIGINT,
  ts AS TO_TIMESTAMP_LTZ(`datetime`, 3),
  WATERMARK FOR ts AS ts - INTERVAL '4' SECOND
) WITH (
  'connector' = 'kafka',
  'topic' = 'nx-bid',
  'properties.bootstrap.servers' = 'kafka:29092',
  'properties.group.id' = 'flink-q4-bid',
  'scan.startup.mode' = 'earliest-offset',
  'format' = 'json',
  'json.ignore-parse-errors' = 'false'
);
CREATE TABLE sink_q4 (`category` BIGINT, `avgp` DOUBLE) WITH (
  'connector' = 'kafka',
  'topic' = '__OUT__',
  'properties.bootstrap.servers' = 'kafka:29092',
  'format' = 'json',
  'sink.delivery-guarantee' = 'at-least-once'
);
INSERT INTO sink_q4
SELECT A.category AS category, AVG(CAST(B.price AS DOUBLE)) AS avgp FROM auction AS A JOIN bid AS B ON A.id = B.auction GROUP BY A.category;
