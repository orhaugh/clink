-- Nexmark qcum on flink, KAFKA-SINK sink variant. NOT a nexmark query.
-- Cumulative bids per bidder over a 10s window stepping 2s: the panes share a
-- start and end at successive steps, so a bid contributes to every pane of
-- its window that ends after it and the pane count depends on where in the
-- window it falls. Here the two dialects agree on argument order - clink is
-- CUMULATE(time, STEP, SIZE) and Flink is CUMULATE(TABLE, DESCRIPTOR, STEP,
-- SIZE) - which is the opposite situation to HOP above, and the reason each
-- is written out per dialect rather than assumed to follow the other.
-- GENERATED by queries/gen_queries.py from the single cross-engine
-- definition. Edit that file, not this one.
CREATE TABLE bid (
  `auction` BIGINT, `bidder` BIGINT, `price` BIGINT, `channel` STRING, `url` STRING, `datetime` BIGINT,
  ts AS TO_TIMESTAMP_LTZ(`datetime`, 3),
  WATERMARK FOR ts AS ts - INTERVAL '4' SECOND
) WITH (
  'connector' = 'kafka',
  'topic' = 'nx-bid',
  'properties.bootstrap.servers' = 'kafka:29092',
  'properties.group.id' = 'flink-qcum-bid',
  'scan.startup.mode' = 'earliest-offset',
  'format' = 'json',
  'json.ignore-parse-errors' = 'false'
);
CREATE TABLE sink_qcum (`bidder` BIGINT, `num` BIGINT) WITH (
  'connector' = 'kafka',
  'topic' = '__OUT__',
  'properties.bootstrap.servers' = 'kafka:29092',
  'format' = 'json',
  'sink.delivery-guarantee' = 'at-least-once'
);
INSERT INTO sink_qcum
SELECT bidder, COUNT(*) AS num FROM TABLE(CUMULATE(TABLE bid, DESCRIPTOR(ts), INTERVAL '2' SECOND, INTERVAL '10' SECOND)) GROUP BY window_start, window_end, bidder;
