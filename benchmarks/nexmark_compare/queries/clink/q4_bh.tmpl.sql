-- Nexmark q4 on clink, BLACKHOLE sink variant. Average price per category:
-- auction joined to bid, then aggregated. REDUCED from the official q4, which
-- first takes the maximum bid per auction; this averages every bid in the
-- category, so both engines run one join plus one aggregate. Flink casts the
-- price to DOUBLE explicitly and clink does not, which is a DIALECT
-- difference for the same intent: AVG of an exact numeric type returns an
-- exact numeric type in Flink, so AVG(BIGINT) truncates - measured at 49975.0
-- where clink gives 49975.9 - while clink's AVG already returns a real
-- number. clink cannot take the cast inside AVG (its AVG accepts only a bare
-- column reference), so the cast goes where it is needed.
-- GENERATED by queries/gen_queries.py from the single cross-engine
-- definition. Edit that file, not this one.
CREATE TABLE auction (id BIGINT, itemname VARCHAR, initialbid BIGINT, reserve BIGINT, expires BIGINT, seller BIGINT, category BIGINT, datetime BIGINT)
  WITH (connector='kafka', format='json', brokers='__BROKERS__', topic='nx-auction',
        group_id='clink-q4bh-auction', auto_offset_reset='earliest',
        event_time_column='datetime', watermark_lag_ms='4001');
CREATE TABLE bid (auction BIGINT, bidder BIGINT, price BIGINT, channel VARCHAR, url VARCHAR, datetime BIGINT)
  WITH (connector='kafka', format='json', brokers='__BROKERS__', topic='nx-bid',
        group_id='clink-q4bh-bid', auto_offset_reset='earliest',
        event_time_column='datetime', watermark_lag_ms='4001');
CREATE TABLE sink_q4 (category BIGINT, avgp DOUBLE) WITH (connector='blackhole');
INSERT INTO sink_q4
SELECT A.category AS category, AVG(B.price) AS avgp FROM auction AS A JOIN bid AS B ON A.id = B.auction GROUP BY A.category;
